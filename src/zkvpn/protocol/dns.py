"""DNS leak protection for ZK-VPN.

Sends DNS queries through the tunnel and blocks plain DNS / DNS-over-TLS on every
other interface. Works on the three common resolver setups, detected at runtime:

* ``resolved``   -- systemd-resolved (Ubuntu, Fedora, Arch...): per-link DNS with a
                    ``~.`` routing domain, reverted with ``resolvectl revert``.
* ``resolvconf`` -- Debian-style resolvconf / openresolv: a dedicated record.
* ``file``       -- plain ``/etc/resolv.conf`` (containers, Alpine, minimal systems).

``connect`` and ``disconnect`` are separate processes, so what is needed to undo
the change (backend, original resolv.conf) is persisted in a RAM-backed state file
(``/run/zkvpn``, mode 0600), never in process memory only.

DNS-over-HTTPS cannot be filtered by port; the kill-switch (all non-tunnel traffic
dropped) is what covers it.
"""

import asyncio
import json
import logging
import os
import shutil
import subprocess
from pathlib import Path
from typing import Dict, List, Optional, Sequence, Tuple

from zkvpn.core.config import settings

logger = logging.getLogger(__name__)

CHAIN = "ZKVPN_DNS"
RESOLV_CONF = Path("/etc/resolv.conf")
Command = Tuple[str, ...]


def parse_servers(value: str) -> List[str]:
    return [s.strip() for s in value.split(",") if s.strip()]


def render_resolv_conf(servers: Sequence[str]) -> str:
    return "# Generated by ZK-VPN\n" + "".join(f"nameserver {s}\n" for s in servers)


def dns_rules(interface: str) -> List[Command]:
    """iptables/ip6tables commands: only the tunnel (and loopback) may send DNS."""
    cmds: List[Command] = []
    for tool in ("iptables", "ip6tables"):
        cmds += [
            (tool, "-N", CHAIN),
            (tool, "-F", CHAIN),
            (tool, "-A", CHAIN, "-o", interface, "-j", "RETURN"),
            (tool, "-A", CHAIN, "-o", "lo", "-j", "RETURN"),
            (tool, "-A", CHAIN, "-p", "udp", "--dport", "53", "-j", "DROP"),
            (tool, "-A", CHAIN, "-p", "tcp", "--dport", "53", "-j", "DROP"),
            (tool, "-A", CHAIN, "-p", "tcp", "--dport", "853", "-j", "DROP"),   # DNS-over-TLS
            (tool, "-D", "OUTPUT", "-j", CHAIN),
            (tool, "-I", "OUTPUT", "1", "-j", CHAIN),
        ]
    return cmds


def dns_rules_teardown() -> List[Command]:
    cmds: List[Command] = []
    for tool in ("iptables", "ip6tables"):
        cmds += [(tool, "-D", "OUTPUT", "-j", CHAIN),
                 (tool, "-F", CHAIN),
                 (tool, "-X", CHAIN)]
    return cmds


class DNSProtector:
    """DNS leak protection manager."""

    def __init__(self, interface: str = None):
        self.interface = interface or settings.wireguard_interface
        self._dns_servers = parse_servers(settings.dns_servers)
        self._state_file = Path(settings.state_dir) / "dns.json"
        self._protected = self._load_state() is not None

    # ------------------------------------------------------------------ state
    def _load_state(self) -> Optional[Dict]:
        try:
            return json.loads(self._state_file.read_text())
        except (OSError, ValueError):
            return None

    def _save_state(self, state: Dict) -> None:
        self._state_file.parent.mkdir(parents=True, mode=0o700, exist_ok=True)
        fd = os.open(self._state_file, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
        with os.fdopen(fd, "w") as f:
            json.dump(state, f)

    def _clear_state(self) -> None:
        try:
            self._state_file.unlink()
        except FileNotFoundError:
            pass

    # --------------------------------------------------------------- plumbing
    async def _run(self, cmd: Sequence[str], stdin: Optional[str] = None) -> int:
        proc = await asyncio.create_subprocess_exec(
            *cmd,
            stdin=asyncio.subprocess.PIPE if stdin is not None else asyncio.subprocess.DEVNULL,
            stdout=asyncio.subprocess.DEVNULL,
            stderr=asyncio.subprocess.DEVNULL,
        )
        await proc.communicate(stdin.encode() if stdin is not None else None)
        return proc.returncode

    async def detect_backend(self) -> str:
        """Pick how to configure the resolver (``settings.dns_backend`` can force it)."""
        forced = settings.dns_backend
        if forced != "auto":
            return forced
        if shutil.which("resolvectl") and await self._run(["resolvectl", "status"]) == 0:
            return "resolved"
        if shutil.which("resolvconf"):
            return "resolvconf"
        return "file"

    # ---------------------------------------------------------------- backends
    async def _apply(self, backend: str, state: Dict) -> None:
        servers = self._dns_servers
        if backend == "resolved":
            for cmd in (["resolvectl", "dns", self.interface, *servers],
                        ["resolvectl", "domain", self.interface, "~."],
                        ["resolvectl", "default-route", self.interface, "yes"]):
                if await self._run(cmd) != 0:
                    raise RuntimeError(f"{' '.join(cmd)} failed")
        elif backend == "resolvconf":
            rc = await self._run(["resolvconf", "-a", self.interface],
                                 stdin=render_resolv_conf(servers))
            if rc != 0:
                raise RuntimeError("resolvconf -a failed")
        elif backend == "file":
            target = RESOLV_CONF.resolve()         # follow a symlinked resolv.conf
            state["backup"] = target.read_text() if target.exists() else None
            state["target"] = str(target)
            state["written"] = render_resolv_conf(servers)
            self._save_state(state)                 # persist the backup BEFORE touching the file
            target.write_text(state["written"])     # in place: also works on bind-mounted files
        else:
            raise ValueError(f"unknown DNS backend {backend!r}")

    async def _revert(self, state: Dict) -> None:
        backend = state["backend"]
        if backend == "resolved":
            await self._run(["resolvectl", "revert", state["interface"]])
        elif backend == "resolvconf":
            await self._run(["resolvconf", "-d", state["interface"]])
        elif backend == "file":
            target = Path(state["target"])
            if target.exists() and target.read_text() != state["written"]:
                logger.warning("resolv.conf changed since ZK-VPN wrote it; leaving it untouched")
            elif state.get("backup") is not None:
                target.write_text(state["backup"])

    # ------------------------------------------------------------------ public
    async def enable_protection(self) -> bool:
        """Route DNS through the tunnel and block it elsewhere."""
        if self._load_state():
            await self.disable_protection()         # never stack on top of a previous run
        try:
            backend = await self.detect_backend()
            state = {"backend": backend, "interface": self.interface}
            await self._apply(backend, state)
            self._save_state(state)
            await self._block_dns_leaks()
            self._protected = True
            logger.info(f"DNS protection enabled ({backend}) with servers: {self._dns_servers}")
            return True
        except Exception as e:
            logger.error(f"Failed to enable DNS protection: {e}")
            state = self._load_state()
            if state:                                # roll back whatever was applied
                await self._revert(state)
                self._clear_state()
            return False

    async def disable_protection(self) -> bool:
        """Undo :meth:`enable_protection`, even from a different process."""
        try:
            await self._remove_dns_blocks()
            state = self._load_state()
            if state:
                await self._revert(state)
                self._clear_state()
            self._protected = False
            logger.info("DNS protection disabled")
            return True
        except Exception as e:
            logger.error(f"Failed to disable DNS protection: {e}")
            return False

    async def _block_dns_leaks(self) -> None:
        for cmd in dns_rules(self.interface):
            rc = await self._run(cmd)
            if rc != 0 and cmd[1] not in ("-N", "-D"):
                raise RuntimeError(f"firewall rule failed: {' '.join(cmd)}")

    async def _remove_dns_blocks(self) -> None:
        for cmd in dns_rules_teardown():
            await self._run(cmd)

    async def test_leaks(self) -> dict:
        """Test for DNS/IPv6 leaks."""
        results = {"dns_leak": False, "ipv6_leak": False, "dns_servers": [], "public_ip": None}
        try:
            dns_servers = await self._get_current_dns_servers()
            results["dns_servers"] = dns_servers
            for server in dns_servers:
                if server not in self._dns_servers and not server.startswith("10."):
                    results["dns_leak"] = True
                    logger.warning(f"DNS leak detected: {server}")
            results["ipv6_leak"] = await self._check_ipv6()
            results["public_ip"] = await self._get_public_ip()
        except Exception as e:
            logger.error(f"Leak test failed: {e}")
        return results

    async def _get_current_dns_servers(self) -> List[str]:
        """DNS servers currently configured."""
        servers: List[str] = []
        try:
            if RESOLV_CONF.exists():
                for line in RESOLV_CONF.read_text().splitlines():
                    parts = line.split()
                    if len(parts) >= 2 and parts[0] == "nameserver":
                        servers.append(parts[1])
        except Exception as e:
            logger.debug(f"Failed to read DNS servers: {e}")
        return servers

    async def _check_ipv6(self) -> bool:
        """True if IPv6 is configured on a non-tunnel interface (possible leak)."""
        try:
            result = await asyncio.to_thread(
                subprocess.run, ["ip", "-6", "-o", "addr", "show", "scope", "global"],
                capture_output=True, text=True, timeout=5)
            return any(self.interface not in line for line in result.stdout.splitlines())
        except Exception:
            return False

    async def _get_public_ip(self) -> Optional[str]:
        """Current public IP address as seen from outside."""
        for service in ("https://api.ipify.org", "https://icanhazip.com", "https://ifconfig.me"):
            try:
                proc = await asyncio.create_subprocess_exec(
                    "curl", "-s", "-m", "5", service,
                    stdout=asyncio.subprocess.PIPE, stderr=asyncio.subprocess.DEVNULL)
                stdout, _ = await proc.communicate()
                ip = stdout.decode().strip()
                if ip:
                    return ip
            except Exception:
                continue
        return None

    @property
    def is_protected(self) -> bool:
        """True while protection is active (survives process restarts)."""
        return self._protected or self._load_state() is not None


# Global DNS protector instance
dns_protector = DNSProtector()

__all__ = ["DNSProtector", "dns_protector", "dns_rules", "dns_rules_teardown",
           "render_resolv_conf", "parse_servers"]
